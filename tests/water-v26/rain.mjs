roof=6;const before=hits.length;
for(let i=0;i<120;i++)rain.update(1/60,{state,camera,chunks:new Map(),rain:1});
assert.equal(hits.length,before,'Shelter suppresses ground impacts');
assert(Array.from(rain.uniforms.uRainFloor.value.image.data).every(x=>x===6),'Rain vertex clipping sees roof support');
