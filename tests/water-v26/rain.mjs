const rain=createRainRenderer(scene,{rng,onRipple:p=>hits.push(p),surfaceQuery:()=>({y:0,roof,water})});
for(let i=0;i<120;i++)rain.update(1/60,{state,camera,chunks:new Map(),rain:1});
assert.equal(rain.statistics.batches,3);assert.equal(rain.rain.geometry.instanceCount,2600);
