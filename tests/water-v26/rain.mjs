assert.deepEqual(rain.uniforms.uRainCameraVelocity.value.toArray(),[3,0,2]);
const attrs=rain.rings.children.flatMap(m=>Object.values(m.geometry.attributes).filter(a=>a.isInstancedBufferAttribute));
const versions=attrs.map(a=>a.version),seedVersion=rain.rain.geometry.attributes.rainSeed.version;
rain.update(.005,{state,camera,chunks:new Map(),rain:0});
assert.deepEqual(attrs.map(a=>a.version),versions,'No per-frame surface particle buffer upload');
assert.equal(rain.rain.geometry.attributes.rainSeed.version,seedVersion,'Rain seeds immutable');
assert(!rain.rain.visible&&rain.rings.visible,'Finished rain preserves fading impact effects');
state.cx+=1n;state.x-=64;camera.position.x-=64;
rain.update(.005,{state,camera,chunks:new Map(),rain:0});
assert.deepEqual(rain.uniforms.uRainRebase.value.toArray(),[-64,0]);
assert.deepEqual(attrs.map(a=>a.version),versions,'Chunk rebase uses uniform, no per-particle transforms');
