# encode Blender per-vertex bake (bake134.py output) into a JS data module: base64 u8 RGBM per welded vertex
# rgb*a = sqrt(B/R), B = baked outgoing radiance per unit albedo (linear), R = 16
import sys,json,struct,array,base64,math
SRC,BIN,OUT,NAME=sys.argv[1:5];R=16.0;SMOOTH=int(sys.argv[5]) if len(sys.argv)>5 else 0
d=json.load(open(SRC));f=open(BIN,'rb');res={};tot=0;mx=0
for m in d['meshes']:
    n=struct.unpack('<I',f.read(4))[0];a=array.array('f');a.frombytes(f.read(n*16))
    assert n==m['count'],(n,m['count'])
    out=bytearray(n*4)
    for i in range(n):
        c=[math.sqrt(max(0.0,min(R,a[i*4+k]))/R) for k in range(3)];M=max(c+[1e-6]);A=min(255,max(1,math.ceil(M*255)));s=A/255
        out[i*4:i*4+4]=bytes([min(255,round(c[0]/s*255)),min(255,round(c[1]/s*255)),min(255,round(c[2]/s*255)),A])
        mx=max(mx,max(a[i*4:i*4+3]))
    res[m['key']]=base64.b64encode(bytes(out)).decode();tot+=n
with open(OUT,'w') as o:
    o.write('// Generated by tools/bake134_blender.py + encode134.py (V134-blender): Blender Cycles per-vertex lighting (direct + 4 diffuse bounces, soft shadows, emissive fixtures).\n')
    o.write('// Key = mesh name|vertex count|n (collectBake133 L=.3); value = base64 u8 RGBM per weld133 vertex: B = (rgb*a)^2*16 = outgoing radiance per unit albedo. Applied by venue134-bake.js; off with ?bake=0.\n')
    o.write('export const %s=%s;\n'%(NAME,json.dumps(res,separators=(',',':'))))
print('verts',tot,'max',mx)
