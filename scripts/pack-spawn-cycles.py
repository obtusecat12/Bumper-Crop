"""Pack linear Cycles irradiance into a small, opaque quadratic-linear WebP."""
from pathlib import Path
import json,numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter
root=Path(__file__).resolve().parents[1];src=root/'art-source/level0-spawn-cycles';m=json.loads((src/'bake.json').read_text());n=m['size'];p=m['padding']
raw=np.fromfile(src/'irradiance.f32',dtype=np.float32).reshape(n,n,4);out=np.zeros((n,n,3),np.float32)
for f in m['faces']:
    x,y,w,h=f['rect'];v=gaussian_filter(raw[y:y+h,x:x+w,:3],sigma=(1.6,1.6,0));out[y-p:y+h+p,x-p:x+w+p]=np.pad(v,((p,p),(p,p),(0,0)),mode='edge')
encoded=np.uint8(np.clip(np.sqrt(np.maximum(out,0)/12),0,1)*255+.5)
target=root/'dist/assets/level0-spawn-cycles';target.mkdir(parents=True,exist_ok=True)
Image.fromarray(encoded[::-1]).save(target/'irradiance.webp',lossless=True,method=6)
(root/'dist/level0-spawn-cycles-data.js').write_text('// Generated by scripts/pack-spawn-cycles.py.\nexport const SPAWN_BAKE='+json.dumps(m,separators=(',',':'))+';\n')
print('Packed', (target/'irradiance.webp').stat().st_size, 'bytes; irradiance max',float(out.max()))
