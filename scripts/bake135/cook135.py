# V135-capital ②c: cook the merged cell bake db (encode135 output, {key: base64 u8}) into per-cell binary packs.
# usage: python3 cook135.py db.json cellmap.json dist/capital135
# out: <out>/c<ix>_<iz>.bin (raw u8 concatenation) + <out>/index.js (CAPITAL135_INDEX = {"ix,iz":{f,n,k:[[key,off,len],..]}})
import sys,json,base64,os,hashlib
DB,CM,OUT=sys.argv[1:4];db=json.load(open(DB));cm=json.load(open(CM));os.makedirs(OUT,exist_ok=True)
for f in os.listdir(OUT):
  if f.endswith('.bin'):os.remove(os.path.join(OUT,f))
cells={}
for k in sorted(db):
  c=tuple(cm[k]);cells.setdefault(c,[]).append(k)
idx={};tot=0
for c,keys in sorted(cells.items()):
  buf=bytearray();ent=[]
  for k in keys:
    b=base64.b64decode(db[k]);ent.append([k,len(buf),len(b)]);buf+=b
  h=hashlib.sha1(buf).hexdigest()[:8];fn='c%d_%d.%s.bin'%(c[0],c[1],h)
  open(os.path.join(OUT,fn),'wb').write(buf);tot+=len(buf)
  idx['%d,%d'%c]={'f':fn,'n':len(buf),'k':ent}
with open(os.path.join(OUT,'index.js'),'w') as o:
  o.write('// Generated by bc/scripts/bake135/cook135.py (V135-capital ②c): per-cell index of the Blender Cycles capital bake packs.\n')
  o.write('// Each cell pack = raw u8 rgba per weld133 vertex, meshes concatenated; streamed by capital135-stream.js.\n')
  o.write('export const CAPITAL135_INDEX=%s;\n'%json.dumps(idx,separators=(',',':')))
print('cells',len(idx),'keys',sum(len(v['k']) for v in idx.values()),'bytes',tot)
