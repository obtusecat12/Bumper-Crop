# V135-capital ②c-2: copy Blender HLOD output (hlod135.py) into dist with content-hashed names + index module.
# usage: python3 cookhlod135.py /workspace/work/v135h/out dist/capital135/hlod [min_hi_tris]
import sys,json,os,hashlib,shutil
SRC,OUT=sys.argv[1:3];MIN=int(sys.argv[3]) if len(sys.argv)>3 else 1500
os.makedirs(OUT,exist_ok=True)
for f in os.listdir(OUT):os.remove(os.path.join(OUT,f))
rep=json.load(open(os.path.join(SRC,'hlod.json')));idx={};tot=0
for k,v in sorted(rep.items()):
  if v['hi']<MIN:continue
  ix,iz=k.split(',');e={'hi':v['hi'],'lo':v['lo']}
  for ext,key in (('bin','b'),('jpg','t')):
    p=os.path.join(SRC,'h%s_%s.%s'%(ix,iz,ext));b=open(p,'rb').read();h=hashlib.sha1(b).hexdigest()[:8];fn='h%s_%s.%s.%s'%(ix,iz,h,ext)
    open(os.path.join(OUT,fn),'wb').write(b);e[key]=fn;tot+=len(b)
  idx[k]=e
with open(os.path.join(OUT,'index.js'),'w') as o:
  o.write('// Generated by bc/scripts/bake135/cookhlod135.py (V135-capital ②c-2): per-cell HLOD proxies (Blender merge+Decimate+Cycles atlas).\n')
  o.write('export const CAPITAL135_HLOD=%s;\n'%json.dumps(idx,separators=(',',':')))
print('cells',len(idx),'bytes',tot)
