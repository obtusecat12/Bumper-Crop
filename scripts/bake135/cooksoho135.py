# V135-capital ③-3c: cook the SoHo block bake (encode135.py db with keys "ix,iz#meshkey") into one pack per streamed block.
# usage: python3 cooksoho135.py db.json dist/capital135/soho
# out: b<ix>_<iz>.<sha8>.bin (raw u8 rgba per weld133 vertex, meshes concatenated) + index.js (SOHO135_INDEX = {"ix,iz":{f,n,k:[[key,off,len]]}})
# The dump (kit /workspace/work/v135w/dumpsoho.js) keys each block with soho135-bake.js prepSoho135 + keySky133, exactly as the game does.
import sys,json,base64,os,hashlib
DB,OUT=sys.argv[1:3];db=json.load(open(DB));os.makedirs(OUT,exist_ok=True)
for f in os.listdir(OUT):
  if f.endswith('.bin'):os.remove(os.path.join(OUT,f))
blocks={}
for k in sorted(db):
  b,mk=k.split('#',1);blocks.setdefault(b,[]).append((mk,k))
idx={};tot=0
for b,keys in sorted(blocks.items()):
  buf=bytearray();ent=[]
  for mk,k in keys:
    u=base64.b64decode(db[k]);ent.append([mk,len(buf),len(u)]);buf+=u
  ix,iz=b.split(',');fn='b%s_%s.%s.bin'%(ix,iz,hashlib.sha1(buf).hexdigest()[:8])
  open(os.path.join(OUT,fn),'wb').write(buf);tot+=len(buf);idx[b]={'f':fn,'n':len(buf),'k':ent}
with open(os.path.join(OUT,'index.js'),'w') as o:
  o.write('// Generated by bc/scripts/bake135/cooksoho135.py (V135-capital ③-3c): per-block index of the Blender Cycles SoHo bake packs.\n')
  o.write('// Each pack = raw u8 rgba per weld133 vertex (rgb = sqrt(bounce/2), a = sky visibility), meshes concatenated; filled by soho135-bake.js.\n')
  o.write('export const SOHO135_INDEX=%s;\n'%json.dumps(idx,separators=(',',':')))
print('blocks',len(idx),'keys',sum(len(v['k']) for v in idx.values()),'bytes',tot)
