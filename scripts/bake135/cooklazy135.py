#!/usr/bin/env python3
# V135-capital ②c-2b-2b: data for the "deferred" capital roots (photo landmarks createReferenceScenes, milling mouth).
# Their geometry is still built by the original builders, but only on the first L10/L11 update (exit-scene loadGeo,
# while the geometry packs download); at boot exit-scene needs just the root head (name/matrix/userData.cityStats)
# + colliders + walks, cooked here.
# Input: lazy.json from the kit page /workspace/work/v135f/dumplazy.js on city.html?scene=city&bake=0&cook135=0.
# Usage: python3 cooklazy135.py lazy.json bc/dist/capital135/geo   -> lazy.js (CAPITAL135_LAZY)
# JSON turns NaN into null: the only non-finite numbers in this data are NaN (milling circle colliders ry=NaN, checked
# with /workspace/work/v135f/chk.js), so every null is written back as NaN to stay bit-identical.
import json, os, sys
d = json.load(open(sys.argv[1])); out = sys.argv[2]
p = os.path.join(out, 'lazy.js')
body = json.dumps(d, separators=(',', ':')).replace(':null', ':NaN')
open(p, 'w').write('// generated by bc/scripts/bake135/cooklazy135.py (V135-capital ②c-2b-2b)\nexport const CAPITAL135_LAZY=' + body + ';\n')
print({k: (len(v['colliders']), len(v['walks'])) for k, v in d.items()}, os.path.getsize(p))
