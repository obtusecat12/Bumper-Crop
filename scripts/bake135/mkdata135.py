# write dist/capital135-bake-data.js from the merged cell db (encode135.py output)
import sys,json
DB,OUT=sys.argv[1:3];db=json.load(open(DB));cells=sys.argv[3] if len(sys.argv)>3 else ''
with open(OUT,'w') as o:
  o.write('// Generated by bc/scripts/bake135 (V135-capital): Blender 5.1 Cycles per-vertex OUTDOOR bake of the fixed L11 fabric, per 112 m city cell (%s).\n'%cells)
  o.write('// Same format as city-bake133-data.js (u8 rgba per weld133 vertex: rgb = sqrt(bounce/2), a = sky visibility); overrides CITY_BAKE133 per key. Off: ?bake135=0.\n')
  o.write('export const CAPITAL135_BAKE=%s;\n'%json.dumps(db,separators=(',',':')))
print('keys',len(db))
