#!/usr/bin/env python3
# V135-capital ②c-2b-2: cook the fixed capital batch roots (approach, rural verge, joined ground, clinic district,
# landmark fabric + ground) into gzip geometry packs, lossless (bit-identical Float32 arrays -> same bake keys).
# Input: raw.json from the kit dump page (/workspace/work/v135f/dump.js on city.html?scene=city&bake=0&cook135=0).
# Output: dist/capital135/geo/<root>.<sha8>.bin  = gzip([u32 jsonLen][json node tree][pad4][attribute data])
#         dist/capital135/geo/index.js         = CAPITAL135_GEO {state, order, roots:{name:{f, head, ...builder fields}}}
# Usage: python3 cookgeo135.py raw.json bc/dist/capital135/geo
import json, base64, gzip, hashlib, os, struct, sys, glob
src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src)); os.makedirs(out, exist_ok=True)
for f in glob.glob(os.path.join(out, '*.bin')): os.remove(f)
index = {'v': 1, 'state': d['state'], 'order': list(d['roots'].keys()), 'roots': {}}
tot = 0
for k, v in d['roots'].items():
    data = base64.b64decode(v['b64']); tree = v['tree']
    js = json.dumps(tree, separators=(',', ':')).encode()
    pad = (4 - (4 + len(js)) % 4) % 4
    raw = struct.pack('<I', len(js)) + js + b' ' * pad + data
    z = gzip.compress(raw, 9, mtime=0)
    h = hashlib.sha1(z).hexdigest()[:8]; fn = f'{k}.{h}.bin'
    open(os.path.join(out, fn), 'wb').write(z); tot += len(z)
    head = {a: b for a, b in tree.items() if a != 'c'}
    index['roots'][k] = {'f': fn, 'head': head, **v['meta']}
    print(k, len(raw), '->', len(z))
open(os.path.join(out, 'index.js'), 'w').write('// generated by bc/scripts/bake135/cookgeo135.py (V135-capital ②c-2b-2)\nexport const CAPITAL135_GEO=' + json.dumps(index, separators=(',', ':')) + ';\n')
print('total', tot, 'index', os.path.getsize(os.path.join(out, 'index.js')))
