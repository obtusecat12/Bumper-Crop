#!/usr/bin/env python3
"""Generates dist/scroll131.css (V131-scrollbars). Slices from tools/scroll131_assets.py."""
import os
B='./assets/ui-v131sb/'
def theme(t,scopes,w,cap,grip):
    S=lambda p: ','.join(s+' *'+p for s in scopes)
    u=lambda n: f"url({B}{t}/{n}.png)"
    o=[]
    o.append(f"{S('::-webkit-scrollbar')}{{width:{w}px;height:{w}px;background:transparent}}")
    o.append(f"{S('::-webkit-scrollbar-track:vertical')}{{background:{u('track-v')} 0 0/{w}px auto repeat-y;image-rendering:pixelated}}")
    o.append(f"{S('::-webkit-scrollbar-track:horizontal')}{{background:{u('track-h')} 0 0/auto {w}px repeat-x;image-rendering:pixelated}}")
    if t=='w7':
        o.append(f"{S('::-webkit-scrollbar-track-piece:vertical:active')}{{background:{u('track-a-v')} 0 0/{w}px auto repeat-y}}")
        o.append(f"{S('::-webkit-scrollbar-track-piece:horizontal:active')}{{background:{u('track-a-h')} 0 0/auto {w}px repeat-x}}")
    for st,ps in (('n',''),('h',':hover'),('a',':active')):
        g=f"{u('grip-'+st+'-v')} center/8px 7px no-repeat," if grip else ''
        gh=f"{u('grip-'+st+'-h')} center/7px 8px no-repeat," if grip else ''
        gc='padding-box,' if grip else ''
        o.append(f"{S('::-webkit-scrollbar-thumb:vertical'+ps)}{{border:solid transparent;border-width:{cap}px 0;"
                 f"background:{g}{u('thumb-top-'+st+'-v')} top/{w}px {cap}px no-repeat,{u('thumb-bot-'+st+'-v')} bottom/{w}px {cap}px no-repeat,{u('thumb-body-'+st+'-v')} 0 0/{w}px 1px repeat-y;"
                 f"background-origin:border-box;background-clip:{gc}border-box,border-box,padding-box;image-rendering:pixelated;min-height:{max(24,2*cap+12)}px}}")
        o.append(f"{S('::-webkit-scrollbar-thumb:horizontal'+ps)}{{border:solid transparent;border-width:0 {cap}px;"
                 f"background:{gh}{u('thumb-top-'+st+'-h')} left/{cap}px {w}px no-repeat,{u('thumb-bot-'+st+'-h')} right/{cap}px {w}px no-repeat,{u('thumb-body-'+st+'-h')} 0 0/1px {w}px repeat-x;"
                 f"background-origin:border-box;background-clip:{gc}border-box,border-box,padding-box;image-rendering:pixelated;min-width:{max(24,2*cap+12)}px}}")
    o.append(f"{S('::-webkit-scrollbar-button')}{{display:none;width:{w}px;height:{w}px}}")
    for ax,a,b in (('vertical','up','down'),('horizontal','up','down')):
        sfx='v' if ax=='vertical' else 'h'
        o.append(f"{S('::-webkit-scrollbar-button:'+ax+':start:decrement')},{S('::-webkit-scrollbar-button:'+ax+':end:increment')}{{display:block;image-rendering:pixelated}}")
        for st,ps in (('n',''),('h',':hover'),('a',':active')):
            o.append(f"{S('::-webkit-scrollbar-button:'+ax+':start:decrement'+ps)}{{background:{u('btn-'+a+'-'+st+'-'+sfx)} 0 0/{w}px {w}px no-repeat}}")
            o.append(f"{S('::-webkit-scrollbar-button:'+ax+':end:increment'+ps)}{{background:{u('btn-'+b+'-'+st+'-'+sfx)} 0 0/{w}px {w}px no-repeat}}")
    o.append(f"{S('::-webkit-scrollbar-corner')}{{background:{u('corner-v')} 0 0/{w}px {w}px}}")
    return o
W7=['html[data-ui-level="11"]','html[data-ui-level="27"]','#venue-map']
AQ=['html[data-ui-level="1"]','html[data-ui-level="10"]']
css=['/* V131-scrollbars (generated by bc/tools/gen_scroll131_css.py — edit the generator, not this file).',
' w7 = 2009 Win7/Vista Aero grey bars on the Goggle Maps pages (L11, L27, venue maps); aq = Leopard Aqua on L1/L10.',
' L0 keeps the 98.css bars from vendor/98css; this file only unblocks them. Firefox gets scrollbar-color. */',
'@supports selector(::-webkit-scrollbar){',
# Chromium >=121: scrollbar-color/width on an element disable ::-webkit-scrollbar → reset them where we skin
','.join(s+' *' for s in W7+AQ+['html[data-ui-level="0"]'])+'{scrollbar-color:auto!important;scrollbar-width:auto!important}']
css+=theme('w7',W7,17,3,True)+theme('aq',AQ,15,7,False)
import re
v98=open(os.path.join(os.path.dirname(__file__),'..','dist','vendor','98css','98-level0.css')).read()
# 98-level0.css scrollbar rules use :root[..] + :vertical/:start — dropped by Chromium; re-emit them html-scoped
def rescope(rule):
    sel,body=rule.split('{',1)
    out=[]
    for one in sel.split(',:root'):
        one=(':root'+one if not one.startswith(':root') else one).strip()
        tail=one.split(') *',1)[1]
        out+=[f'html[data-ui-level="0"] {a} *{tail}' for a in ('.w98','.modal:not(.map-modal)','.hud-actions')]
    return ','.join(out)+'{'+body
rules=re.findall(r':root\[data-ui-level="0"\][^{}]*::-webkit-scrollbar[^{}]*\{[^}]*\}',v98)
css+=['/* L0: 98.css scrollbar rules re-scoped (Chromium drops :root/:is + scrollbar pseudo-classes) */']+[rescope(r) for r in rules]
css+=[','.join(f'html[data-ui-level="0"] {a} *::-webkit-scrollbar-button' for a in ('.w98','.modal:not(.map-modal)','.hud-actions'))+'{width:16px;height:17px}']
css+=['}','@supports not selector(::-webkit-scrollbar){',
','.join(s+' *' for s in W7)+'{scrollbar-color:#c2c2c2 #ededed!important;scrollbar-width:auto!important}',
','.join(s+' *' for s in AQ)+'{scrollbar-color:#3f7fd6 #f3f3f3!important;scrollbar-width:auto!important}',
'html[data-ui-level="0"] *{scrollbar-color:#c0c0c0 #dfdfdf!important}','}']
open(os.path.join(os.path.dirname(__file__),'..','dist','scroll131.css'),'w').write('\n'.join(css)+'\n')
print('ok')
